#!/usr/bin/env node
/**
 * Build script for ruv-swarm WASM module
 */

import { rustSourceDigest, recordWasmBuild } from './wasm-provenance.js';
import fs from 'fs/promises';
import path from 'path';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function build() {
  console.log('Building ruv-swarm WASM module...\n');

  const npmDir = path.join(__dirname, '..');
  const crateDir = path.join(npmDir, '..', 'crates', 'ruv-swarm-wasm');
  const wasmDir = path.join(npmDir, 'wasm');
  const wasmSIMDDir = path.join(npmDir, 'wasm-simd');
  const sourceSha256 = await rustSourceDigest(path.resolve(npmDir, '../..'));
  const baseFlags = process.env.RUSTFLAGS || '';
  const simdFlags = `${baseFlags} -C target-feature=+simd128`.trim();

  try {
    if (process.env.CARGO_ENCODED_RUSTFLAGS) {
      throw new Error('Unset CARGO_ENCODED_RUSTFLAGS so the recorded core/SIMD RUSTFLAGS take effect');
    }
    // Check if wasm-pack is installed
    try {
      execFileSync('wasm-pack', ['--version'], { stdio: 'ignore' });
    } catch (error) {
      console.error('Error: wasm-pack is not installed.');
      console.error('Install it with: cargo install wasm-pack --version 0.15.1 --locked');
      process.exit(1);
    }

    // Check if Rust is installed
    try {
      execFileSync('rustc', ['--version'], { stdio: 'ignore' });
    } catch (error) {
      console.error('Error: Rust is not installed.');
      console.error('Install it from: https://rustup.rs/');
      process.exit(1);
    }

    // Create output directories
    await fs.mkdir(wasmDir, { recursive: true });
    await fs.mkdir(wasmSIMDDir, { recursive: true });
    await fs.rm(path.join(wasmDir, 'build-info.json'), { force: true });

    // Build standard WASM module
    console.log('Building standard WASM module...');
    execFileSync('wasm-pack', ['build', '--release', '--target', 'web', '--out-dir', wasmDir, '--', '--locked'],
      { cwd: crateDir, stdio: 'inherit', env: { ...process.env, RUSTFLAGS: baseFlags } });

    // Build SIMD-optimized module
    console.log('\nBuilding SIMD-optimized WASM module...');
    execFileSync('wasm-pack', ['build', '--release', '--target', 'web', '--out-dir', wasmSIMDDir, '--', '--locked'], {
      cwd: crateDir, stdio: 'inherit',
      env: { ...process.env, RUSTFLAGS: simdFlags },
    });

    // Copy SIMD module to main wasm directory
    const simdWasmPath = path.join(wasmSIMDDir, 'ruv_swarm_wasm_bg.wasm');
    const simdTargetPath = path.join(wasmDir, 'ruv_swarm_simd.wasm');
    await fs.copyFile(simdWasmPath, simdTargetPath);
    // wasm-pack writes an ignore-all file for standalone publishing. This
    // repository commits the generated artifacts and the receipt for consumers.
    await fs.rm(path.join(wasmDir, '.gitignore'), { force: true });
    const generatedManifestPath = path.join(wasmDir, 'package.json');
    const generatedManifest = JSON.parse(await fs.readFile(generatedManifestPath, 'utf8'));
    generatedManifest.private = true;
    await fs.writeFile(generatedManifestPath, `${JSON.stringify(generatedManifest, null, 2)}\n`);

    // Reuse wasm-bindgen's actual public declarations instead of a handwritten
    // approximation that can drift from the compiled module.
    await fs.writeFile(path.join(npmDir, 'src', 'wasm-types.d.ts'),
      "// Generated by scripts/build.js.\nexport * from '../wasm/ruv_swarm_wasm.js';\n");

    // Clean up temporary SIMD directory
    await fs.rm(wasmSIMDDir, { recursive: true, force: true });

    await recordWasmBuild(npmDir, {
      sourceSha256,
      artifacts: ['ruv_swarm_wasm_bg.wasm', 'ruv_swarm_simd.wasm', 'ruv_swarm_wasm.js',
        'ruv_swarm_wasm.d.ts', 'ruv_swarm_wasm_bg.wasm.d.ts', 'package.json', 'wasm-bindings-loader.mjs'],
      configurations: [
        { name: 'core', artifacts: ['ruv_swarm_wasm_bg.wasm'], rustFlags: baseFlags,
          target: 'wasm32-unknown-unknown', bindingTarget: 'web', profile: 'release', defaultFeatures: true, features: [] },
        { name: 'simd', artifacts: ['ruv_swarm_simd.wasm'], rustFlags: simdFlags,
          target: 'wasm32-unknown-unknown', bindingTarget: 'web', profile: 'release', defaultFeatures: true, features: [] },
      ],
      toolchain: {
        rustc: execFileSync('rustc', ['--version'], { encoding: 'utf8' }).trim(),
        wasmPack: execFileSync('wasm-pack', ['--version'], { encoding: 'utf8' }).trim(),
      },
    });

    console.log('\nBuild completed successfully!');
    console.log(`WASM modules are in: ${wasmDir}`);

  } catch (error) {
    console.error('\nBuild failed:', error.message);
    process.exit(1);
  }
}

// Run build
build();
